export function operationalStatus(locale: AppLocale, value: string) {
  const pair = statusLabels[value];
  if (pair) return locale === 'ta-IN' ? pair[1] : pair[0];
  return value.replaceAll('_', ' ');
}

export function useOperationalTranslations() {
  const { locale } = useLanguage();
  return {
    locale,
    t: (key: OperationalKey) => catalogs[locale][key] ?? english[key],
    status: (value: string) => operationalStatus(locale, value),
  };
}
