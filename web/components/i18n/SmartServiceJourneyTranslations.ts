const catalogs = { 'en-IN': english, 'ta-IN': tamil } as const;

export function interpolateSmartServiceJourney(template: string, values: Record<string, string | number>) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function useSmartServiceJourneyTranslations() {
  const { locale } = useLanguage();
  return useMemo(() => ({
    locale,
    t: (key: SmartServiceJourneyKey) => catalogs[locale][key] ?? english[key],
  }), [locale]);
}
